// Usage: node packages/engine/src/merino-cli.ts [data/merino-court/building] [--out data/merino-court/feng-shui]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { merinoPlans } from "./adapters/merino.ts";
import { rate } from "./index.ts";

const args = process.argv.slice(2);
const oi = args.indexOf("--out");
const out = oi >= 0 ? args[oi + 1] : null;
const dir = args.find((a, i) => !a.startsWith("--") && i !== oi + 1) ?? "data/merino-court/building";
const { north, scored, skipped } = merinoPlans(
  JSON.parse(readFileSync(join(dir, "plans.json"), "utf8")), JSON.parse(readFileSync(join(dir, "trace.json"), "utf8")), readFileSync(join(dir, "building.yaml"), "utf8"));
const rows = scored.map(({ unit, plan }) => ({ unit, plan, r: rate(plan) })).sort((a, b) => b.r.score - a.r.score || b.r.courtyard.raw - a.r.courtyard.raw);
const lines = [
  `# Merino Court feng shui ranking (FloorQi engine)`, ``,
  `Generated by \`node packages/engine/src/merino-cli.ts\`. Page-up = ${north}° true (building.yaml). Score = 80 + PLAN.md rules + 4 x Courtyard raw, clamped 0-100.`,
  `Courtyard raw is the Goswell Road model (Eight Mansions + Flying Star period 9 + form); views are unknown here, so the garden/street factor is skipped.`, ``,
  `| Rank | Unit | Level | Score | Grade | Courtyard raw | Facing | Chart | Main findings |`, `|---|---|---|---|---|---|---|---|---|`,
  ...rows.map(({ unit, plan, r }, i) => `| ${i + 1} | ${unit.key} (${unit.name}) | ${plan.level} | ${r.score} | ${r.grade} | ${r.courtyard.raw >= 0 ? "+" : ""}${r.courtyard.raw} | ${r.courtyard.facing?.toFixed(1)}° | ${r.courtyard.labels.join(" / ")} | ${r.findings.filter((f) => f.delta).sort((a, b) => Math.abs(b.delta) - Math.abs(a.delta)).slice(0, 4).map((f) => `${f.rule_id} ${f.delta > 0 ? "+" : ""}${f.delta}`).join(", ")} |`),
  ``, `Not scored:`, ...skipped.map((s) => `- ${s.unit.key} (${s.unit.name}): ${s.reason}`), ``,
  `Caveats: rooms are the brochure's label boxes (rectangles), doors/windows are traced from the photographed brochure, hob/WC positions are room centres, and the entrance comes from the traced "IN" marker.`,
];
console.log(lines.join("\n"));
if (out) {
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "ranking.md"), lines.join("\n") + "\n");
  writeFileSync(join(out, "results.json"), JSON.stringify(rows.map(({ unit, r }) => ({ unit: unit.key, name: unit.name, ...r })), null, 1) + "\n");
  for (const { unit, plan } of rows) writeFileSync(join(out, `${unit.key}.floorplan.json`), JSON.stringify(plan, null, 1) + "\n");
}
